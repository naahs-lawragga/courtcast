import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {webcrypto} from 'node:crypto';
import vm from 'node:vm';
const source=readFileSync('courtcast-security.js','utf8');
globalThis.crypto ??= webcrypto;
vm.runInThisContext(source);
const s=globalThis.CCSecurity,t=s.newToken();
assert.match(t,/^[a-f0-9]{32}$/);
assert.notEqual(t,s.newToken());
assert(s.inviteValid(t,1000,false,999));
assert(!s.inviteValid(t,1000,false,1000));
assert(!s.inviteValid(t,1000,true,999));
assert(s.validRequest({type:'request',force:false,token:t},t));
assert(!s.validRequest({type:'request',force:'true',token:t},t));
assert(!s.validRequest({type:'request',force:true,token:s.newToken()},t));
assert(!s.validRequest({type:'request',force:true,token:t,extra:1},t));
assert(s.validMedia({kind:'courtcast-v9-media',token:t},t));
assert(!s.validMedia({kind:'courtcast-v9-media',token:'wrong'},t));
assert(s.validMessage({type:'state',sharing:true}));
assert(!s.validMessage({type:'state',sharing:1}));
assert(!s.validMessage({type:'orientation',angle:100,landscape:true,mobile:true,width:1,height:1}));
assert(!s.validMessage({type:'quality',label:'x'.repeat(81)}));
assert(!s.validMessage(null));
assert.equal(s.normalizeName('  Gamer   42  '),'Gamer 42');
assert.equal(s.normalizeName('<script>'),'');
assert.equal(s.normalizeName('x'.repeat(25)),'');
assert.equal(s.normalizeName('A\u202eB'),'');
assert(s.validManual({kind:'courtcast-v9-manual',name:'Gamer 42'}));
assert(!s.validManual({kind:'courtcast-v9-manual',name:'<img src=x>'}));
assert(!s.validManual({kind:'courtcast-v9-manual'}));
assert(!s.validManual({kind:'courtcast-v9-manual',name:'Gamer',extra:true}));
let now=1;const gate=s.rateGate(2,100,()=>now);
assert(gate());assert(gate());assert(!gate());now=101;assert(gate());
const html=readFileSync('index.html','utf8'),app=readFileSync('courtcast-app.js','utf8');
new vm.Script(app);
assert(!/<script(?:\s[^>]*)?>\s*[^<\s]/i.test(html),'No inline scripts');
assert(!/<[^>]+\son[a-z]+\s*=/i.test(html),'No inline handlers');
assert(html.includes('courtcast-security.js')&&html.includes('courtcast-app.js'));
const config=JSON.parse(readFileSync('vercel.json','utf8'));
const headers=new Map(config.headers[0].headers.map(x=>[x.key,x.value]));
assert(headers.get('Content-Security-Policy').includes("frame-ancestors 'none'"));
assert(!headers.get('Content-Security-Policy').split(';').find(x=>x.trim().startsWith('script-src ')).includes("'unsafe-inline'"));
assert.equal(headers.get('X-Frame-Options'),'DENY');
assert.equal(headers.get('X-Content-Type-Options'),'nosniff');
console.log('CourtCast protocol and security configuration tests passed.');
